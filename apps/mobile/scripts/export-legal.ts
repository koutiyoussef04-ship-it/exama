/**
 * Writes the public versions of the Privacy Policy and Terms of Use from the in-app text in
 * src/i18n/legal.ts, so the app, the repository docs and the website always say the same thing:
 *   - docs/legal/privacy-policy.md, docs/legal/terms-of-use.md (all languages, Markdown)
 *   - website/src/data/legal.generated.json (rendered at exama.app/privacy, /terms and their
 *     /es, /fr, /ar versions; the website is a separate project, so it reads this data file
 *     instead of importing app code)
 *   npm run legal:export -w @study/mobile
 * test/legal.test.ts fails if any of these files is out of date.
 */
import { writeFileSync } from 'node:fs';
import { LEGAL, LEGAL_IS_DRAFT, LEGAL_MISSING, LEGAL_UPDATED, type LegalDoc } from '../src/i18n/legal';

const LANG_NAMES = { en: 'English', es: 'Español', fr: 'Français', ar: 'العربية' } as const;

export function renderLegalMarkdown(doc: 'privacy' | 'terms'): string {
  const out: string[] = [];
  if (LEGAL_IS_DRAFT) {
    out.push('> **DRAFT — not ready to publish.** Replace every `[bracketed]` item and `{{placeholder}}`, have the text reviewed, then set `LEGAL_IS_DRAFT = false` in `apps/mobile/src/i18n/legal.ts`. Generated from that file — edit it there and run `npm run legal:export -w @study/mobile`.', '');
  }
  for (const lang of Object.keys(LEGAL) as (keyof typeof LEGAL)[]) {
    const d: LegalDoc = LEGAL[lang][doc];
    out.push(`# ${d.title} (${LANG_NAMES[lang]})`, '', `_Last updated: ${LEGAL_UPDATED}_`, '');
    for (const s of d.sections) out.push(`## ${s.heading}`, '', s.body, '');
    out.push('---', '');
  }
  return out.join('\n');
}

/** The data the website renders. Same text as the app; {{company}}/{{email}}/{{address}} are filled by the website. */
export function renderLegalWebsiteJson(): string {
  const data = {
    $comment: 'GENERATED by apps/mobile/scripts/export-legal.ts from apps/mobile/src/i18n/legal.ts. Do not edit by hand.',
    updated: LEGAL_UPDATED,
    isDraft: LEGAL_IS_DRAFT,
    languages: Object.keys(LEGAL),
    languageNames: LANG_NAMES,
    missing: LEGAL_MISSING,
    docs: LEGAL,
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}

export const LEGAL_FILES = { privacy: '../../../docs/legal/privacy-policy.md', terms: '../../../docs/legal/terms-of-use.md' } as const;
export const LEGAL_WEBSITE_FILE = '../../../website/src/data/legal.generated.json';

if (process.argv[1]?.endsWith('export-legal.ts')) {
  for (const [doc, path] of Object.entries(LEGAL_FILES)) {
    writeFileSync(new URL(path, import.meta.url), renderLegalMarkdown(doc as 'privacy'));
    console.log(`wrote ${path}`);
  }
  writeFileSync(new URL(LEGAL_WEBSITE_FILE, import.meta.url), renderLegalWebsiteJson());
  console.log(`wrote ${LEGAL_WEBSITE_FILE}`);
}
