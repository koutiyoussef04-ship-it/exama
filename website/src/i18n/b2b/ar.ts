const n = (v: number) => new Intl.NumberFormat('ar-u-nu-latn', { useGrouping: 'always' }).format(v);
/**
 * A number with its noun in the form Arabic grammar asks for after it: plural for 3–10 (and 103–110…), accusative singular
 * for 11–99, singular for 100, 1,000, 2,000…, so the wording stays correct if the plans' figures change.
 */
type ArNoun = { sing: string; acc: string; plural: string };
const count = (v: number, w: ArNoun) => {
  const r = v % 100;
  const form = r >= 3 && r <= 10 ? w.plural : r >= 11 ? w.acc : w.sing;
  return `${n(v)} ${form}`;
};
